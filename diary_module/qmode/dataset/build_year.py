def _pick(rng, pool):
    return rng.choice(pool) if pool else ""


def _compose(rng, bank, qid: str, ph: dict) -> str:
    """문항 프레임 + 국면 재료 → 답변 한 개.

    길이를 일부러 흩뜨린다: 짧은 답변(게이트 미달)이 섞여야 aggregate.py 의
    길이 게이트가 실제로 작동하는 걸 데모로 보여줄 수 있다.
    """
    p = ph["key"]
    frame = _pick(rng, FRAMES[qid])
    # 어휘 다이얼: approach 확률로 능동/회피 톤을 고른다(같은 국면 안에서도 흔들림)
    react_pool = bank["react"][p]
    slots = {
        "sit": _pick(rng, bank["sit"][p]),
        "react": _pick(rng, react_pool),
        "taste": _pick(rng, bank["taste"][p]),
        "rel": _pick(rng, bank["rel"][p]),
        "good": _pick(rng, bank["good"][p]),
        "ins": _pick(rng, bank["ins"][p]),
        "envy": _pick(rng, bank["envy"][p]),
        "deep": _pick(rng, bank["deep"]),
        "future": _pick(rng, bank["future"]),
    }
    text = frame.format(**slots)

    # 15% 는 아주 짧게 자른다(게이트 미달 케이스 확보)
    if rng.random() < 0.15:
        text = text.split(".")[0].strip()
        if len(text) > 12:
            text = text[:12]
    # 20% 는 해석절을 덧붙여 40형태소 이상(가중치 1.0)으로 만든다
    elif rng.random() < 0.20:
        text = text + " " + _pick(rng, bank["ins"][p])
    return text.strip()


def build(persona_key: str, days: int = DAYS, seed: int = 20260810) -> dict:
    bank = BANK[persona_key]
    rng = random.Random(seed + sum(ord(c) for c in persona_key))
    sch = Scheduler(seed=seed)

    history: list[dict] = []
    out_days: list[dict] = []
    for i in range(days):
        d = START + timedelta(days=i)
        ph = phase_of(i)
        qs = sch.pick(d.isoformat(), history, user_day=i)
        qids = [q["id"] for q in qs]
        history.append({"date": d.isoformat(), "question_ids": qids})

        # 적응률 — 그날 기록했는가. 주말은 조금 낮게.
        adh = ph["adherence"] * (0.82 if d.weekday() >= 5 else 1.0)
        if rng.random() > adh:
            continue

        # 그날 낸 문항 중 일부만 답하는 날도 있다(실사용에 가깝게)
        answered = [q for q in qids if rng.random() < 0.88] or qids[:1]
        answers = {qid: _compose(rng, bank, qid, ph) for qid in answered}
        free = _pick(rng, FREE[ph["key"]]) if rng.random() < 0.12 else None
        out_days.append({"day": i, "date": d.isoformat(), "answers": answers, "free": free})

    n_ans = sum(len(x["answers"]) for x in out_days)
    return {
        "persona": persona_key,
        "name": bank["profile_note"],
        "note": (f"1년치 데모 — {START.isoformat()} 시작 {days}일 중 {len(out_days)}일 기록"
                 f"({len(out_days)/days:.0%}), 답변 {n_ans}개. "
                 f"국면 4개로 성향이 이동하도록 설계(build_year.py 참조). 합성 데이터."),
        "generated_by": "build_year.py",
        "phases": [{"key": p["key"], "name": p["name"], "from_day": p["from"]} for p in PHASES],
        "days": out_days,
    }


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("persona", nargs="?", default=None, help="비우면 전체")
    ap.add_argument("--days", type=int, default=DAYS)
    args = ap.parse_args()

    OUT_DIR.mkdir(exist_ok=True)
    keys = [args.persona] if args.persona else list(BANK)
    for k in keys:
        data = build(k, args.days)
        (OUT_DIR / f"{k}.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
        n_ans = sum(len(x["answers"]) for x in data["days"])
        n_free = sum(1 for x in data["days"] if x["free"])
        print(f"{k:<14} {len(data['days']):>3}일 기록 / {args.days}일  "
              f"답변 {n_ans:>4}개  자유일기 {n_free:>3}개  → diaries_year/{k}.json")

    # 문항 편성은 실제 Scheduler 산출물이므로 함께 저장해 검증 가능하게 남긴다.
    sch = Scheduler(seed=20260810)
    hist, sched = [], []
    for i in range(args.days):
        d = START + timedelta(days=i)
        qids = [q["id"] for q in sch.pick(d.isoformat(), hist, user_day=i)]
        hist.append({"date": d.isoformat(), "question_ids": qids})
        sched.append({"day": i, "date": d.isoformat(),
                      "weekday": "월화수목금토일"[d.weekday()], "question_ids": qids})
    (HERE / f"schedule_{args.days}d.json").write_text(
        json.dumps(sched, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{'schedule':<14} {args.days}일 편성 → schedule_{args.days}d.json")


if __name__ == "__main__":
    main()
