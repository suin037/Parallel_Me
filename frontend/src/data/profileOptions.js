// 프로필 선택지 상수 — 화면마다 흩어져 있던 목록을 한 곳으로.
//
// 앱에는 '직종'이라 불리는 값이 **두 개** 있고 서로 다른 축이다.
//   · OCCUPATIONS       — 온보딩·설정에서 고르는 분류. 사람이 자기를 소개하는 말.
//                         (예측 모델의 피처는 아니다. 화면 표기·서사 톤에만 쓴다)
//   · OCCUPATION_GROUPS — 시뮬레이션 입력의 KSCO 대분류 1~9. 이건 실제로 모델이
//                         쓰는 값(profile.occupation_group)이다.
//
// 왜 파일로 뺐나: 온보딩(Onboarding.jsx)과 설정(Settings.jsx)이 각자 OCCUPATIONS 를
// 들고 있었는데 **내용이 달랐다**. 온보딩에만 "설치·정비·생산"·"건설·농림·기타"가,
// 설정에만 "건설·생산·운송"·"학생·취업준비"가 있었다. 한쪽에서 고른 직종이 다른 쪽
// 드롭다운엔 없으니 선택이 안 된 것처럼 보이고, 그 상태로 저장하면 값이 날아간다.
// ─────────────────────────────────────────────────────────────

export const OCCUPATIONS = [
  "연구·공학기술",
  "경영·사무·금융·보험",
  "교육·법률·복지·공공",
  "보건·의료",
  "예술·디자인·방송",
  "영업·판매·서비스",
  "설치·정비·생산",
  "건설·농림·운송",
  "학생·취업준비",
  "기타",
];

export const OCCUPATION_GROUPS = [
  [1, "관리자"], [2, "전문가·관련 종사자"], [3, "사무 종사자"],
  [4, "서비스 종사자"], [5, "판매 종사자"], [6, "농림어업 숙련 종사자"],
  [7, "기능원·관련 기능 종사자"], [8, "장치·기계 조작·조립 종사자"], [9, "단순노무 종사자"],
];

const GROUP_LABEL = Object.fromEntries(OCCUPATION_GROUPS);

// 사용자가 고른 적 없는데 저장돼 있던 값들. 예전 기본 프로필이 넣던 "사회계열"은
// 어느 드롭다운에도 없어서, 화면에는 뜨는데 설정에서는 찾을 수 없는 유령이었다.
const PHANTOM = new Set(["사회계열"]);

/**
 * 화면에 보여줄 직종 한 줄. 사용자가 고른 적 없으면 빈 문자열(자리를 비운다).
 *
 * 목록에 없는 값이라고 버리지는 않는다 — 목록이 갈라져 있던 시절에 저장된
 * 정상적인 선택("건설·생산·운송" 등)이 있어서, 화이트리스트로 막으면 사용자가
 * 분명히 고른 직종이 화면에서 사라진다.
 */
/** KSCO 대분류 코드 → 이름. 코드만 들고 있는 화면(API 결과 표시)이 쓴다. */
export function occupationGroupLabel(code) {
  if (code == null || code === "") return "";
  return GROUP_LABEL[Number(code)] || "";
}

export function occupationLabel(profile) {
  const picked = (profile?.occupation || "").trim();
  if (picked && !PHANTOM.has(picked)) return picked;
  // 없으면 시뮬레이션 입력에서 고른 KSCO 대분류로 대신한다 — 이것도 사용자가
  // 직접 고른 직종이고, 오히려 모델이 실제로 쓰는 값이다.
  return GROUP_LABEL[profile?.occupation_group] || "";
}
