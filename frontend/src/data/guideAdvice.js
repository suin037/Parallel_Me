// 첫 사용 안내(Tour)와 역할이 다르다. Tour 는 어느 버튼인지 한 줄로 짚고 지나간다.
// 여기는 그 화면에 **머무는 동안** 자세히 알려준다 — 이 숫자가 뭔지, 눌러볼 수
// 있는 게 또 있는지, 왜 이렇게 만들었는지.
//
// 누가 나오는가 — result.js 의 MASCOTS 역할 그대로 맡긴다.
//   · 루미(별빛 가이드)   기록과 별자리를 돌본다 → 일기 · 별자리 · 보관함 · 설정
//   · 코스모(행성 탐험가) 데이터와 결과를 분석한다 → 나의 우주 · 행성 · 결과
//   · 노바(유성 가이드)   기회와 변화를 전한다 → 시뮬레이션
// 말투도 그 성격을 따른다. 루미는 다정하게, 코스모는 담백하게, 노바는 활기차게.
//
// 화면에 상시로 붙여두지 않는다. 늘 떠 있으면 아는 사람에게는 방해일 뿐이다.
// '가이드 확인하기'를 켠 사람에게만 따라다니고, 닫으면 그걸로 꺼진다.
// ─────────────────────────────────────────────────────────────
import storage from "./safeStorage.js";

const ON = "pm.advice.on.v1";

export function adviceOn() {
  return storage.getItem(ON) === "1";
}

export function setAdvice(on) {
  if (on) storage.setItem(ON, "1");
  else storage.removeItem(ON);
  if (typeof window !== "undefined") window.dispatchEvent(new Event("pm:advice"));
}

/**
 * 열린 패널이 자기가 열렸다고 알린다("planet" | "cluster" | null).
 * 행성·별자리는 '나의 우주' 위에 뜨는 화면이라 라우트만으로는 구분이 안 된다.
 */
export function announceSurface(key) {
  if (typeof window === "undefined") return;
  window.dispatchEvent(new CustomEvent("pm:advice-surface", { detail: key || null }));
}

