// ─────────────────────────────────────────────────────────────
// 기분 색 — 이 앱에서 '그날 기분 1~5' 를 색으로 말하는 유일한 자리.
//
// 왜 모았나: 같은 축을 네 곳(별자리·홈 캘린더·기록 아카이브·행성 패널)이 각각
//   복사해 쓰고 있었고, 그 사이에 값이 갈라져 있었다 — 레벨 5 가 어디선 보라(#8B6CCF),
//   어디선 파랑(#378ADD)이었다. 같은 5점이 화면마다 다른 색이면 규칙이 아니라 장식이 된다.
//
// 규칙 — 톤온톤. 색상(hue)은 브랜드 보라 계열 하나로 고정하고, **밝기만** 움직인다.
//   1) 축은 하나다 — 그날 기분 1~5. 좋고 나쁨 말고 다른 뜻을 얹지 않는다.
//   2) 색상 계열은 바뀌지 않는다. 다섯 색 모두 남보라~라벤더(hue 245~262) 안에 있다.
//      계열을 넘나들면(빨강↔초록) 색 자체가 뜻을 갖는 것처럼 보여서 배경 위에서 튄다.
//   3) 밝기가 1에서 5로 단조 증가한다. 이게 유일한 신호다 —
//      **어두운 별 = 힘들었던 날, 밝은 별 = 좋았던 날.**
//      별 크기(Constellation 의 r)도 같은 방향이라 색과 크기가 서로 어긋나지 않는다.
//
// 왜 밝기인가: 실제 밤하늘에서 별을 구분하는 것도 밝기다. 규칙을 한 줄로 설명할 수 있어야
//   범례(MoodLegend)에 그대로 적을 수 있고, 사용자가 한 번 보면 외운다.
//
// 전에 쓰던 램프(#E24B4A 빨강 → #D85A30 주황 → #EDA100 노랑 → #5DCAA5 초록 → 파랑/보라)는
//   신호등이었다. 밝기 순서도 없고, 초록은 앱 전체에서 여기서만 쓰는 색이라 배경(#070D19)
//   위에서 혼자 튀었다. 색이 강해질수록 별이 아니라 아이콘처럼 보인다.
//
// 채도를 낮게 잡은 이유: 이 색들은 UI 가 아니라 밤하늘에 찍히는 점이다.
//   버튼·강조색(#8B6CCF)보다 튀면 별이 인터페이스를 이긴다.
// ─────────────────────────────────────────────────────────────

/**
 * 기분 1~5 별빛. 인덱스 = level - 1. 계열은 하나, 밝기만 오른다.
 *
 * 폭을 넓게 잡았다(가장 어두운 쪽은 배경에 가깝고, 가장 밝은 쪽은 거의 흰빛).
 * 계열이 하나뿐이라 신호가 밝기밖에 없는데, 다섯 칸을 좁게 두면 별이 4~5px 로
 * 찍히는 화면에서 옆 단계와 구분이 안 된다. 색만으로 부족해서 Constellation 이
 * 같은 레벨로 헤일로 세기와 별 크기까지 함께 키운다(세 신호가 같은 방향).
 */
export const MOOD_COLORS = ["#3F4A73", "#6B6CA6", "#9B93D2", "#C9BCF6", "#F5F1FF"];

/** 같은 램프의 옅은 짝 — 헤일로·큰 면적처럼 색이 넓게 깔리는 자리에 쓴다. */
export const MOOD_COLORS_SOFT = ["#5F6B98", "#8B8CC2", "#B3ABE2", "#DCD2FB", "#FBF9FF"];

/** 별 하나의 밝기(투명도). 색만으로 모자란 차이를 여기서 한 번 더 벌린다. */
export const MOOD_ALPHA = [0.62, 0.76, 0.88, 0.96, 1];

/** 별 둘레 헤일로의 진하기 — 좋은 날일수록 넓게 번진다. */
export const MOOD_GLOW = [0.04, 0.07, 0.11, 0.17, 0.26];

/** 기록이 없는 날. 램프의 가장 어두운 1번보다 더 어둡고 채도가 없어야 '안 쓴 날'로 읽힌다. */
export const MOOD_EMPTY = "#2B3350";

/** 범례에 적는 한 줄. 화면마다 다르게 쓰면 규칙이 아니게 된다. */
export const MOOD_RULE_LINE = "별은 밝기로 말해요 — 어두울수록 힘들었던 날, 밝을수록 좋았던 날.";

export const MOOD_LABELS = ["매우 낮음", "낮음", "보통", "좋음", "매우 좋음"];

/** mood(1~5) 또는 valence(-1~1) → 레벨 1~5. 둘 다 없으면 보통. */
export function moodLevel(star) {
  if (star?.mood != null) return Math.max(1, Math.min(5, Math.round(star.mood)));
  if (star?.valence != null) return Math.max(1, Math.min(5, Math.round(star.valence * 2 + 3)));
  return 3;
}

export function moodColor(star) {
  return MOOD_COLORS[moodLevel(star) - 1];
}

/** 평균 기분(소수)처럼 레벨이 아닌 값을 색으로 바꿀 때. 없으면 null. */
export function moodColorOf(value) {
  if (value == null || !Number.isFinite(Number(value))) return null;
  return MOOD_COLORS[Math.max(0, Math.min(4, Math.round(Number(value)) - 1))];
}
