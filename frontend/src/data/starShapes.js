// 별 개수 → 그 개수로 그릴 수 있는 모양들.
const BY_COUNT = SHAPES.reduce((acc, shape) => {
  (acc[shape.points.length] ||= []).push(shape);
  return acc;
}, {});

/**
 * 기록 개수에 맞는 별자리 뼈대를 고른다.
 * seed 가 같으면 항상 같은 모양이 나온다 — 새로고침마다 별자리가 바뀌면 '내 별자리'가 아니다.
 */
export function starShapeFor(count, seed = 0) {
  const n = Math.max(1, Math.min(7, count | 0));
  const pool = BY_COUNT[n] || BY_COUNT[1];
  return pool[Math.abs(Math.round(seed)) % pool.length];
}

/** 문자열(별자리 id·날짜)을 seed 정수로. 같은 별자리는 늘 같은 모양을 받는다. */
export function seedFrom(text) {
  let hash = 0;
  for (let i = 0; i < String(text).length; i++) hash = (hash * 31 + String(text).charCodeAt(i)) | 0;
  return Math.abs(hash);
}
