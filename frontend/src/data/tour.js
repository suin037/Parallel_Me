//
// 다음만 눌러도 처음부터 끝까지 이어지도록 짰다. 그대로 화면 녹화를 하면
// 사용 안내 영상이 된다.
//
// 누가 말하는가 — result.js 의 MASCOTS 역할 그대로다.
//   · 코스모(행성 탐험가) 데이터와 결과를 분석한다 → 나의 우주 · 행성 · 결과 · 기업분석
