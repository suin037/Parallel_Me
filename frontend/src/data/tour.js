//   · 노바(유성 가이드)   기회와 변화를 전한다     → 시뮬레이션
//
// 대상은 data-tour="키" 로 찾는다. 그 화면에 없는 단계(결과가 아직 없을 때의
// 결과 화면 등)는 조용히 건너뛴다 — 빈 스포트라이트는 안내가 아니라 고장으로 보인다.
//
// 저장은 safeStorage — 사파리·iframe 에서 localStorage 가 막히면 안내가 아니라
// 앱이 통째로 죽는다.
// ─────────────────────────────────────────────────────────────
